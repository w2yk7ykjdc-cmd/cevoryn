/**
 * Sprint 22 Phase 2: provider-agnostic execution types. Every type here is
 * deliberately shaped so it can NEVER carry a credential -- `ExecutionAccount`/
 * `ExecutionBalance`/`ExecutionPosition`/`ExecutionOrder` are all pure,
 * already-redacted read models, safe to log, safe to return from an API
 * route, safe to hand to an AI tool (Phase 15's own "AI can explain/
 * inspect/summarize" -- these types are exactly what that would read).
 */

/**
 * `PAPER` -- the existing, unchanged Sprint 16 simulation
 * (`PaperAccount`/`PaperPosition`/`PaperTrade`). `LIVE` -- a real Binance
 * account via `BinanceExecutionAdapter`. Never a third value: this sprint
 * does not introduce a "testnet" or "sandbox" mode as a first-class
 * `ExecutionMode` (a sandbox adapter is used directly in tests instead --
 * see `execution/testing/mock-gateway.ts` -- so the mode enum itself stays
 * exactly the two real, meaningfully-different states callers must branch
 * on).
 */
export type ExecutionMode = "PAPER" | "LIVE";

export type ExecutionAccount = {
  mode: ExecutionMode;
  /** Provider's own account identifier, if it has one meaningfully distinct from the organization itself (e.g. a Binance account uid). `null` for PAPER. */
  providerAccountId: string | null;
  /** True only for LIVE when the account can actually trade right now (not restricted/locked by the provider). Always `true` for PAPER. */
  canTrade: boolean;
};

export type ExecutionBalance = {
  asset: string;
  /** Total balance, as a plain number -- see the module's own doc comment on precision: this is a READ/display value, never fed back into a sizing calculation (which uses the existing Sprint 16 `Decimal`-precision path). */
  total: number;
  available: number;
  locked: number;
};

export type ExecutionPositionSide = "LONG" | "SHORT";

export type ExecutionPosition = {
  symbol: string;
  side: ExecutionPositionSide;
  quantity: number;
  entryPrice: number;
  markPrice: number;
  unrealizedPnl: number;
  leverage: number;
};

export type OrderSide = "BUY" | "SELL";
export type OrderType = "MARKET" | "LIMIT";

/**
 * The lifecycle every `LiveOrder` row (and every PAPER-adapter in-memory
 * equivalent) moves through -- see `prisma/schema.prisma#LiveOrderStatus`'s
 * own doc comment for the exact state-machine contract. Duplicated here as
 * a plain TS union (not re-exported from `@prisma/client`) so the
 * `ExecutionGateway` interface itself has zero Prisma dependency -- a
 * provider adapter is pure application logic, persistence is a separate
 * concern layered on top by `execution/service.ts`.
 */
export type ExecutionOrderStatus =
  | "INTENT"
  | "VALIDATING"
  | "SUBMITTING"
  | "SUBMITTED"
  | "PARTIALLY_FILLED"
  | "FILLED"
  | "CANCEL_REQUESTED"
  | "CANCELLED"
  | "REJECTED"
  | "FAILED";

/**
 * What a caller asks the gateway to do -- built from an already-validated
 * `MarketDecision`/`ProposedOrder` (Sprint 19), never constructed from raw,
 * unchecked numbers. `clientOrderId` is the Phase 6 idempotency key --
 * REQUIRED, deterministic, generated by `execution/idempotency.ts` from the
 * originating decision, never random and never left to the caller to
 * improvise.
 */
export type OrderIntent = {
  clientOrderId: string;
  symbol: string;
  side: OrderSide;
  type: OrderType;
  quantity: number;
  /** Required for `type: "LIMIT"`, ignored for `"MARKET"`. */
  price?: number;
  strategyType: string;
  /**
   * Optional risk-management levels the shared pipeline (Phase 12) already
   * computed via the EXISTING Sprint 16 `buildEntryPlan` before this
   * intent was ever built -- carried through so `PaperExecutionAdapter`
   * can open a fully-shaped position (matching what
   * `paper-trading/generate.ts#openPosition` already persists) rather than
   * a degraded, stop/take-profit-less one. `BinanceExecutionAdapter`
   * ignores these for the base order this sprint (a live bracket/OCO order
   * is documented, honest future work -- see that adapter's own top-level
   * doc comment).
   */
  stopLossPrice?: number;
  takeProfitPrice?: number;
  leverage?: number;
};

export type ExecutionOrder = {
  clientOrderId: string;
  /** The provider's own order id -- `null` until `SUBMITTED` (or later) is reached. */
  providerOrderId: string | null;
  symbol: string;
  side: OrderSide;
  type: OrderType;
  quantity: number;
  price: number | null;
  status: ExecutionOrderStatus;
  filledQuantity: number;
  averageFillPrice: number | null;
  rejectionReason: string | null;
};

/**
 * Every capability an `ExecutionGateway` provider can offer, split apart
 * (Phase 2's own explicit "provider interface ile capability'leri
 * birbirinden ayır") so a future, narrower provider (e.g. a read-only
 * monitoring integration) could implement just `AccountReadCapability`
 * without being forced to also implement order submission. Every real
 * provider this sprint ships (`PaperExecutionAdapter`,
 * `BinanceExecutionAdapter`) implements the full set via the composed
 * `ExecutionGateway` type below.
 */
export interface AccountReadCapability {
  getAccount(): Promise<ExecutionAccount>;
  getBalances(): Promise<ExecutionBalance[]>;
}

export interface PositionReadCapability {
  getOpenPositions(): Promise<ExecutionPosition[]>;
}

export interface OrderReadCapability {
  getOpenOrders(): Promise<ExecutionOrder[]>;
  /** `symbol` is required, not optional -- Binance's own order-status endpoint requires it alongside `clientOrderId` (a lookup by client id alone is not a real Binance capability); every provider implementation must accept it even if a given provider's own API doesn't strictly need it. */
  getOrder(clientOrderId: string, symbol: string): Promise<ExecutionOrder | null>;
}

export interface OrderWriteCapability {
  /**
   * MUST be idempotent on `intent.clientOrderId`: calling this twice with
   * the same `clientOrderId` must never place a second real order --
   * either the provider's own idempotency (Binance's `newClientOrderId`)
   * or (for the paper adapter) an explicit local check. See
   * `execution/service.ts#submitDecision` for the full duplicate-submission
   * guard, which checks the persisted `LiveOrder` row BEFORE ever calling
   * this method at all -- this method's own idempotency is defense in
   * depth, not the only guard.
   */
  submitOrder(intent: OrderIntent): Promise<ExecutionOrder>;
  /** `symbol` required for the same real-API reason `OrderReadCapability.getOrder` requires it. */
  cancelOrder(clientOrderId: string, symbol: string): Promise<void>;
}

/**
 * The full provider-agnostic gateway (Phase 2). `providerName`/`mode` are
 * plain, inspectable metadata -- never used to branch execution-critical
 * logic (that would defeat the point of the abstraction); they exist so
 * logs/audit rows can record which concrete provider handled a given
 * intent.
 */
export interface ExecutionGateway extends AccountReadCapability, PositionReadCapability, OrderReadCapability, OrderWriteCapability {
  readonly providerName: string;
  readonly mode: ExecutionMode;
}
