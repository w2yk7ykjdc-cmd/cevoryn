import { requirePermission } from "@/server/auth/session";
import { getDecisionIntelligenceSnapshot } from "@/server/intelligence/decision-intelligence/service";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";

function percentLabel(value: number | null): string {
  return value === null ? "—" : `${value}%`;
}

/**
 * Fully server-rendered and read-only -- there is nothing to mutate on this
 * page. Every number shown comes directly from
 * `getDecisionIntelligenceSnapshot` (pure database aggregation + a
 * deterministic ranking function); nothing here is generated by an LLM.
 */
export default async function DecisionsPage() {
  const { organization } = await requirePermission({ decision: ["read"] });
  const snapshot = await getDecisionIntelligenceSnapshot(organization.id);

  return (
    <div className="flex flex-col gap-6">
      <div>
        <h1 className="text-2xl font-semibold tracking-tight">Decision Intelligence</h1>
        <p className="text-sm text-muted-foreground">
          Historical performance and evidence-based prioritization for CompanyOS&apos;s open Risks and active
          Opportunities. Ranking is advisory only -- it explains its own reasoning from real evaluated outcome
          data and can never change CompanyOS&apos;s autonomy policy, allowlist, or the recommendation below.
        </p>
      </div>

      <Card>
        <CardHeader>
          <CardTitle>Current top-priority Decision</CardTitle>
          <CardDescription>Sprint 8&apos;s deterministic, rule-based recommendation -- unaffected by this page.</CardDescription>
        </CardHeader>
        <CardContent>
          {snapshot.currentDecision ? (
            <div className="flex flex-col gap-1 text-sm">
              <p className="font-medium">{snapshot.currentDecision.recommendation}</p>
              <p className="text-muted-foreground">{snapshot.currentDecision.rationale}</p>
            </div>
          ) : (
            <p className="text-sm text-muted-foreground">No open Risk or active Opportunity currently requires attention.</p>
          )}
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle>Ranked candidates</CardTitle>
          <CardDescription>
            Every open Risk and active Opportunity, ranked by severity-weighted exposure adjusted by confidence and
            historical success rate.
          </CardDescription>
        </CardHeader>
        <CardContent>
          {snapshot.rankedCandidates.length === 0 ? (
            <p className="text-sm text-muted-foreground">No open Risk or active Opportunity to rank.</p>
          ) : (
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Kind</TableHead>
                  <TableHead>Title</TableHead>
                  <TableHead>Priority score</TableHead>
                  <TableHead>Reasons</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {snapshot.rankedCandidates.map((candidate) => (
                  <TableRow key={`${candidate.kind}:${candidate.id}`}>
                    <TableCell>
                      <Badge variant={candidate.kind === "risk" ? "destructive" : "default"}>{candidate.kind}</Badge>
                    </TableCell>
                    <TableCell className="font-medium">{candidate.title}</TableCell>
                    <TableCell className="font-mono text-xs">{candidate.priorityScore.toLocaleString()}</TableCell>
                    <TableCell>
                      <ul className="list-disc pl-4 text-xs text-muted-foreground">
                        {candidate.rankingReasons.map((reason, i) => (
                          <li key={i}>{reason}</li>
                        ))}
                      </ul>
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          )}
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle>Rule performance</CardTitle>
          <CardDescription>How reliable is each Sprint 11 evaluation rule, based on evaluated outcomes.</CardDescription>
        </CardHeader>
        <CardContent>
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Rule</TableHead>
                <TableHead>Evaluated</TableHead>
                <TableHead>Success rate</TableHead>
                <TableHead>Avg. confidence</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {snapshot.rulePerformance.map((rule) => (
                <TableRow key={`${rule.ruleName}.${rule.ruleVersion}`}>
                  <TableCell className="text-xs text-muted-foreground">
                    {rule.ruleName}.{rule.ruleVersion}
                  </TableCell>
                  <TableCell>{rule.performance.totalEvaluated}</TableCell>
                  <TableCell>{percentLabel(rule.performance.successRate)}</TableCell>
                  <TableCell>{percentLabel(rule.performance.averageConfidence)}</TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle>Confidence calibration</CardTitle>
          <CardDescription>When CompanyOS reports a given confidence level, how often is the outcome actually positive.</CardDescription>
        </CardHeader>
        <CardContent>
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Confidence bucket</TableHead>
                <TableHead>Evaluated</TableHead>
                <TableHead>Observed success rate</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {snapshot.confidenceCalibration.map((bucket) => (
                <TableRow key={bucket.label}>
                  <TableCell>{bucket.label}</TableCell>
                  <TableCell>{bucket.totalEvaluated}</TableCell>
                  <TableCell>{percentLabel(bucket.observedSuccessRate)}</TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </CardContent>
      </Card>
    </div>
  );
}
