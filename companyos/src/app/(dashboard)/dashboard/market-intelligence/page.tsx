import { requirePermission } from "@/server/auth/session";
import { getMarketIntelligenceRanking } from "@/server/intelligence/market-intelligence/service";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";

function riskBadgeVariant(severity: string): "default" | "secondary" | "destructive" {
  if (severity === "high" || severity === "critical") return "destructive";
  if (severity === "medium") return "secondary";
  return "default";
}

/**
 * Fully server-rendered and read-only -- there is nothing to mutate on
 * this page. Every number shown comes directly from
 * `getMarketIntelligenceRanking` (pure database reads over already-
 * computed Opportunity/Risk/regime data); nothing here is generated by an
 * LLM, and nothing here can place an order, touch an account, or move
 * money. This is intelligence, not a trading terminal.
 */
export default async function MarketIntelligencePage() {
  const { organization } = await requirePermission({ marketIntelligence: ["read"] });
  const snapshot = await getMarketIntelligenceRanking(organization.id);

  return (
    <div className="flex flex-col gap-6">
      <div>
        <h1 className="text-2xl font-semibold tracking-tight">Market Intelligence</h1>
        <p className="text-sm text-muted-foreground">
          Deterministic analysis of public Binance market data -- momentum, trend, volume, volatility, and
          relative strength vs. BTC, ranked by an explainable composite score. No order execution, no account
          access, no financial capability exists anywhere in this pipeline. Not a guarantee of profit.
        </p>
      </div>

      <Card>
        <CardHeader>
          <CardTitle>Market regime</CardTitle>
          <CardDescription>The overall market&apos;s current behavior, classified from BTC&apos;s own metrics.</CardDescription>
        </CardHeader>
        <CardContent>
          {snapshot.regime ? (
            <div className="flex items-center gap-3">
              <Badge>{snapshot.regime}</Badge>
              <span className="text-xs text-muted-foreground">
                {snapshot.regimeObservedAt ? `as of ${new Date(snapshot.regimeObservedAt).toLocaleString()}` : ""}
              </span>
            </div>
          ) : (
            <p className="text-sm text-muted-foreground">No regime data yet -- the market ingestion job has not run.</p>
          )}
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle>Ranked opportunities</CardTitle>
          <CardDescription>Every currently-eligible market opportunity, highest composite score first.</CardDescription>
        </CardHeader>
        <CardContent>
          {snapshot.ranked.length === 0 ? (
            <p className="text-sm text-muted-foreground">No market opportunities currently meet the deterministic eligibility bar.</p>
          ) : (
            <div className="flex flex-col gap-4">
              {snapshot.ranked.map((candidate, index) => (
                <div key={candidate.symbol} className="rounded-lg border p-4">
                  <div className="flex items-center justify-between">
                    <div className="flex items-center gap-2">
                      <span className="text-sm font-semibold text-muted-foreground">#{index + 1}</span>
                      <span className="text-lg font-semibold">{candidate.symbol}</span>
                    </div>
                    <div className="flex items-center gap-2 text-sm">
                      <span>Opportunity: <strong>{candidate.opportunityScore}</strong></span>
                      <Badge variant={riskBadgeVariant(candidate.riskSeverity)}>Risk: {candidate.riskSeverity}</Badge>
                      <span className="text-muted-foreground">Confidence: {candidate.confidence}</span>
                    </div>
                  </div>
                  <ul className="mt-2 list-disc pl-4 text-xs text-muted-foreground">
                    {candidate.reasons.map((reason, i) => (
                      <li key={i}>{reason}</li>
                    ))}
                    {candidate.riskReasons.map((reason, i) => (
                      <li key={`risk-${i}`}>{reason}</li>
                    ))}
                  </ul>
                  <p className="mt-2 text-xs text-muted-foreground">Updated {new Date(candidate.updatedAt).toLocaleString()}</p>
                </div>
              ))}
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  );
}
